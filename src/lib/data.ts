export function getRiskLevelFromPct(pct: number): RiskLevel {
  if (pct >= 50) return "Extreme";
  if (pct >= 40) return "Critical";
  if (pct >= 20) return "Moderate";
  return "Good";
}

/**
 * Heavy Metal Pollution Index (HPI) — a weighted 0-100 composite of the
 * seven tracked metals plus the overall contamination load. Higher = worse.
 */
export const METALS = [
  { key: "arsenic_as_pct", symbol: "As", name: "Arsenic", color: "#ef4444", who: "0.01 mg/L" },
  { key: "chromium_cr_pct", symbol: "Cr", name: "Chromium", color: "#a855f7", who: "0.05 mg/L" },
  { key: "lead_pb_pct", symbol: "Pb", name: "Lead", color: "#fb923c", who: "0.01 mg/L" },
  { key: "cadmium_cd_pct", symbol: "Cd", name: "Cadmium", color: "#facc15", who: "0.003 mg/L" },
  { key: "zinc_zn_pct", symbol: "Zn", name: "Zinc", color: "#38bdf8", who: "3 mg/L" },
  { key: "copper_cu_pct", symbol: "Cu", name: "Copper", color: "#f97316", who: "2 mg/L" },
  { key: "nickel_ni_pct", symbol: "Ni", name: "Nickel", color: "#818cf8", who: "0.07 mg/L" },
] as const;

// relative toxicity weight of each metal (As, Pb, Cd most toxic)
const METAL_TOXICITY: Record<string, number> = {
  arsenic_as_pct: 1.0,
  cadmium_cd_pct: 0.95,
  lead_pb_pct: 0.9,
  chromium_cr_pct: 0.75,
  nickel_ni_pct: 0.55,
  copper_cu_pct: 0.35,
  zinc_zn_pct: 0.25,
};

export function computeHPI(loc: LocationData): number {
  let weighted = 0;
  let weightSum = 0;
  for (const [key, tox] of Object.entries(METAL_TOXICITY)) {
    const share = (loc as unknown as Record<string, number>)[key] || 0;
    weighted += share * tox;
    weightSum += tox;
  }
  const metalScore = weighted / weightSum; // 0-100 (toxicity-weighted metal share)
  const loadScore = (loc.surface_water_pollution_pct + loc.groundwater_pollution_pct) / 2;
  // blend: 55% overall contamination load, 45% toxicity-weighted metal profile
  return Math.round(loadScore * 0.55 + metalScore * 0.45);
}

export function hpiTier(hpi: number): { label: string; color: string } {
  if (hpi >= 55) return { label: "Critical Index", color: "#a855f7" };
  if (hpi >= 40) return { label: "High Index", color: "#ef4444" };
  if (hpi >= 25) return { label: "Elevated Index", color: "#f59e0b" };
  return { label: "Safe Index", color: "#10b981" };
}

